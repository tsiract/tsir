/// Record the publish in the store, and report the deliveries it owes to the SQS queues
/// subscribed to the topic.
///
/// The whole store-touching half of the operation, so the one place that holds the store's
/// lock is the caller's block.
fn publish_into_store(
    store: &mut crate::state::ComAmazonawsSnsAmazonsimplenotificationserviceState,
    input: PublishInput,
    destination: &str,
) -> Result<(PublishOutput, Deliveries), PublishError> {
    let Some(topic) = store.topics.get(destination).cloned() else {
        return Err(PublishErrorModeled::NotFoundException(NotFoundException {
            message: Some(state::TOPIC_DOES_NOT_EXIST.to_string()),
        })
        .into());
    };

    // The rules that need the topic as well as the message: its size ceiling and
    // the FIFO ordering parameters, which also decide the stored deduplication id.
    let request = MessageRequest {
        message: &input.message,
        subject: input.subject.as_deref(),
        message_structure: input.message_structure.as_deref(),
        message_group_id: input.message_group_id.as_deref(),
        message_deduplication_id: input.message_deduplication_id.as_deref(),
        message_attributes: input.message_attributes.as_ref(),
    };
    let message_deduplication_id = match state::topic_message_refusal(&topic, request) {
        Ok(deduplication_id) => deduplication_id,
        Err(reason) => return Err(invalid_parameter(reason)),
    };
    // A FIFO publish is deduplicated: "If a message with a particular
    // MessageDeduplicationId is sent successfully, subsequent messages within the
    // deduplication scope and interval, with the same MessageDeduplicationId, are
    // accepted successfully but aren't delivered"
    // (`PublishInput$MessageDeduplicationId` doc) — so a duplicate answers with the
    // message id and sequence number of the copy that WAS delivered, and nothing is
    // recorded or handed to a queue for it.
    let deduplication_key = message_deduplication_id
        .as_deref()
        .map(|id| state::deduplication_key(&topic, input.message_group_id.as_deref(), id));
    if let Some(accepted) = deduplication_key
        .as_deref()
        .and_then(|key| store.deduplicated_publish(key))
    {
        return Ok((
            PublishOutput {
                message_id: Some(accepted.message_id),
                sequence_number: accepted.sequence_number,
            },
            Deliveries::default(),
        ));
    }
    // Only a FIFO topic is sequenced: "This response element applies only to FIFO
    // (first-in-first-out) topics" (`PublishResponse$SequenceNumber` doc).
    let sequence_number = topic.is_fifo.then(|| store.next_sequence_number());

    let message_id = store.next_unique_id();
    if let Some(key) = deduplication_key {
        store.remember_deduplication(key, &message_id, sequence_number.as_deref());
    }
    // ONE record of the published message, SHARED by every subscription that receives
    // it: the retained log holds handles, not a copy of the body per subscriber.
    let published = ::std::sync::Arc::new(PublishedMessage {
        message_id: message_id.clone(),
        topic_arn: topic.arn.clone(),
        message: ::std::sync::Arc::from(input.message),
        subject: input.subject,
        message_structure: input.message_structure,
        message_attributes: ::std::sync::Arc::new(input.message_attributes.unwrap_or_default()),
        message_group_id: input.message_group_id,
        message_deduplication_id,
        sequence_number: sequence_number.clone(),
        published_at: std::time::SystemTime::now(),
    });

    // SNS "delivers the message to each endpoint that is subscribed to the topic"
    // (Publish doc) — an unconfirmed subscription has no confirmed endpoint yet, so
    // it receives nothing, and a subscription whose filter policy withholds this
    // message receives nothing either. ONE matching budget for the request, so the
    // (subscriptions x conditions x values) product the matching costs is capped.
    let mut matching = state::filter_policy::MatchBudget::new();
    let subscriptions: Vec<state::SubscriptionRecord> = store
        .subscriptions_of(&topic.arn)
        .into_iter()
        .filter(|sub| !sub.pending_confirmation)
        .filter(|sub| state::filter_policy::admits(sub, &published, &mut matching))
        .cloned()
        .collect();
    let deliveries = subscription_deliveries(
        &subscriptions,
        &published,
        Some(&topic),
        &mut DeliveryBudget::new(),
    );
    for subscription in &subscriptions {
        store.record_delivery(&subscription.arn, ::std::sync::Arc::clone(&published));
    }
    // A topic that archives its messages keeps this one too: "ArchivePolicy – The policy
    // that sets the retention period for messages stored in the message archive of an
    // Amazon SNS FIFO topic" (`GetTopicAttributesResponse$Attributes` doc), and the
    // archive is what a subscription's `ReplayPolicy` redelivers from. It is kept whether
    // or not any subscription received the message: a replay exists to reach subscribers
    // that did not exist when the message was published.
    if topic.is_archiving() {
        store.archive_message(
            &topic.arn,
            topic.archive_retention(),
            ::std::sync::Arc::clone(&published),
        );
    }

    Ok((
        PublishOutput {
            message_id: Some(message_id),
            sequence_number,
        },
        deliveries,
    ))
}

/// The ARN namespace of Amazon SQS, whose queues are one of the subscription endpoint kinds
