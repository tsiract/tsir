/**
 * The migrate unit (`DPL-021`, `MIG-012`): a script, deliberately not a function.
 *
 * A migration must run **once**, before the new code takes traffic, and never on cold start.
 * Every platform shape that could be handed a migration — a Worker with a `scheduled`
 * export, a Lambda with an `init` hook, a container's entrypoint — fails that requirement in
 * a different way: a cron runs it every five minutes, a cold start runs it on every new
 * instance, and an entrypoint races itself when the platform scales out.
 *
 * So the artifact is a **program**, not a handler:
 *
 *   · `dist/migrate/<connection>/migrate.mjs` — self-contained, `bun`/`node`-runnable, no
 *     `handler`, no `fetch`, no `scheduled`. There is no shape a platform can invoke, which
 *     is a stronger guarantee than a comment asking people not to.
 *   · It reuses exactly the code path `tsir migrate` uses: the app's own exported `database`
 *     (or `databases` registry), `migrate()` from `@tsir/migrate` with the advisory lock, the
 *     connection's own journal folder and its own audit tables.
 *   · It prints what it did and exits non-zero on any failure, so the deploy pipeline stops
 *     where it should — before the new code is promoted.
 *
 * D1 is refused rather than half-supported: Tsir does not deploy to D1,
 * and a D1 "migration" needs the Worker runtime rather than a script.
 */

import { readFile } from 'node:fs/promises';
import { relative, resolve } from 'node:path';

import { invalidDeployConfig } from '@tsir/deploy';

/** The document that travels with the script, for pipelines and for humans. */
export const MIGRATE_FILE = 'migrate.json';
export const MIGRATE_SCHEMA_VERSION = 1;

export interface MigrateSpec {
  /** The connection name from `tsir.js` (`primary`, `reporting`, …). */
  readonly connection: string;
  /** Absolute path of the application entry — the module that exports the database. */
  readonly entry: string;
  /** Journal folder, relative to the project root. Resolved at run time, not bake time. */
  readonly folder: string;
  /** Driver from `database.connections.<name>.driver`. */
  readonly driver: 'd1' | 'postgres' | 'mysql';
  /** The app that owns it, for the banner. */
  readonly app: string;
  /** Who took the lock — lands in the audit row. */
  readonly actor?: string | undefined;
}

/**
 * The generated script.
 *
 * Absolute paths are **not** baked in: an artifact built on a laptop is run on a deploy
 * machine, where neither `/Users/…` nor `/home/…` exists. `TSIR_MIGRATIONS` overrides, and
 * the default is the folder relative to the working directory, which is the project root by
 * convention (`make migrate` does the same).
 */
export function migrateScriptSource(spec: MigrateSpec): string {
  const actor = spec.actor ?? 'tsir deploy:build';

  return [
    `// Generated by \`tsir deploy:build\` for connection ${JSON.stringify(spec.connection)} — do not edit.`,
    '//',
    '// A program, not a handler: there is no export a platform can invoke, so this cannot run',
    '// on cold start. Run it once per deploy, before the new code takes traffic:',
    '//',
    `//   bun dist/migrate/${spec.connection}/migrate.mjs          # or: node …`,
    '//',
    '// TSIR_MIGRATIONS overrides the journal folder (default: relative to the working directory).',
    `import { migrate } from ${JSON.stringify('@tsir/migrate')};`,
    `import * as app from ${JSON.stringify(spec.entry)};`,
    '',
    `const CONNECTION = ${JSON.stringify(spec.connection)};`,
    `const FOLDER = process.env['TSIR_MIGRATIONS'] ?? ${JSON.stringify(spec.folder)};`,
    '',
    'function fail(message) {',
    '  console.error(`tsir migrate: ${message}`);',
    '  process.exit(1);',
    '}',
    '',
    '// The app owns its database (ADR-0009): one `database` export, or a `databases` registry',
    '// for named connections (ADR-0019). Both are already-built instances — this script does',
    '// not construct a driver, so what runs here is what the app runs.',
    'function databaseFor() {',
    '  const registry = app.databases;',
    '  if (registry !== undefined && typeof registry.connection === "function") {',
    '    const names = registry.names ?? [];',
    `    if (!names.includes(CONNECTION)) {`,
    `      fail(\`the app exports no connection named \${CONNECTION} (declared: \${names.join(", ") || "none"})\`);`,
    '    }',
    '    return registry.connection(CONNECTION);',
    '  }',
    '  const single = app.database;',
    '  if (single === undefined) {',
    '    fail("the application entry exports neither `database` nor `databases` — export the one the app already uses");',
    '  }',
    '  return single;',
    '}',
    '',
    'const database = databaseFor();',
    'console.log(`tsir migrate: ${CONNECTION} · ${FOLDER}`);',
    '',
    'try {',
    '  const result = await migrate({',
    '    database,',
    '    folder: FOLDER,',
    '    name: CONNECTION,',
    `    actor: ${JSON.stringify(actor)},`,
    '    host: process.env["HOSTNAME"],',
    '  });',
    '',
    '  for (const applied of result.applied) console.log(`  + ${applied.tag}`);',
    '  if (result.locked) {',
    '    // Another runner got there first. Not a failure: the schema is at the target state.',
    '    console.log("  · another runner held the lock; nothing applied");',
    '  } else if (result.applied.length === 0) {',
    '    console.log("  · up to date");',
    '  }',
    '  console.log(`  ${result.applied.length} applied · ${result.pending.length} pending · ${result.durationMs} ms`);',
    '',
    '  if (result.drift.length > 0) fail(`drift: ${result.drift.join(", ")}`);',
    '  if (result.pending.length > 0) fail(`${result.pending.length} migration(s) still pending`);',
    '} catch (error) {',
    '  fail(error instanceof Error ? error.message : String(error));',
    '} finally {',
    '  // Close whatever this script opened: `databases` drains every connection, a single',
    '  // `database` closes itself. A one-off script that leaks a pool hangs the pipeline.',
    '  const registry = app.databases;',
    '  const single = app.database;',
    '  try {',
    '    if (registry !== undefined && typeof registry.close === "function") await registry.close();',
    '    else if (single !== undefined && typeof single.close === "function") await single.close();',
    '  } catch {',
    '    // Closing is a courtesy; a failure here must not turn a successful migrate into red.',
    '  }',
    '}',
    'process.exit(0);',
    '',
  ].join('\n');
}

/** Everything a pipeline needs to know about the artifact, without running it. */
export interface MigratePlan {
  readonly schemaVersion: number;
  readonly app: string;
  readonly connection: string;
  readonly driver: string;
  readonly folder: string;
  readonly script: string;
  /** The one-off command. `cwd` is the project root unless `TSIR_MIGRATIONS` says otherwise. */
  readonly command: string;
}

export function migratePlan(spec: MigrateSpec): MigratePlan {
  const script = `migrate/${spec.connection}/migrate.mjs`;
  return {
    schemaVersion: MIGRATE_SCHEMA_VERSION,
    app: spec.app,
    connection: spec.connection,
    driver: spec.driver,
    folder: spec.folder,
    script,
    command: `bun ${script}`,
  };
}

/** The connection a unit name describes: `migrate:primary` → `primary`. */
export function connectionOfUnit(unitName: string): string | undefined {
  return unitName.startsWith('migrate:') ? unitName.slice('migrate:'.length) : undefined;
}

export interface MigrateConnectionConfig {
  readonly driver: 'd1' | 'postgres' | 'mysql';
  readonly folder: string;
}

/**
 * Resolve one migrate unit's spec, refusing what this version cannot do honestly.
 *
 * D1 is the interesting case: Tsir does not deploy to D1, and a
 * migration needs the Worker runtime rather than a script. Refusing with the alternative is
 * better than emitting a script that fails on its first statement.
 */
export function migrateSpec(input: {
  readonly unit: string;
  readonly app: string;
  readonly entry: string;
  readonly root: string;
  readonly connections: Readonly<Record<string, MigrateConnectionConfig>>;
}): MigrateSpec {
  const connection = connectionOfUnit(input.unit);
  if (connection === undefined) {
    throw invalidDeployConfig(`unit "${input.unit}" is not a migrate unit`, { unit: input.unit });
  }

  const config = input.connections[connection];
  if (config === undefined) {
    throw invalidDeployConfig(
      `unit "${input.unit}" names connection "${connection}", which tsir.js does not declare`,
      { unit: input.unit, connection },
    );
  }

  if (config.driver === 'd1') {
    throw invalidDeployConfig(
      `connection "${connection}" is D1, which has no migration script — apply its journal with \`wrangler d1 migrations apply\``,
      { unit: input.unit, connection, driver: config.driver },
    );
  }

  return {
    connection,
    entry: input.entry,
    // Relative on purpose: the artifact is run somewhere else (see `migrateScriptSource`).
    folder: relative(input.root, resolve(input.root, config.folder)),
    driver: config.driver,
    app: input.app,
  };
}

/** Read a file the script will need at run time — kept here so the CLI has one reader. */
export async function readSchema(folder: string): Promise<string | undefined> {
  try {
    return await readFile(folder, 'utf8');
  } catch {
    return undefined;
  }
}
