/**
 * `tsir make:controller <Name> [--path /prefix] [--unit <unit>]` (CLI-010).
 *
 * The output is a plain class with one route, declared with the router's decorators. It takes
 * its dependencies through the constructor and never resolves anything from a container, and
 * it names its deploy unit (RTR-011), so the unit graph is correct from the first generation.
 */

import { join } from 'node:path';

import { parseArgs, stringFlag, boolFlag } from '../args.ts';
import { commitWrites, displayPath, type GeneratedFile, type PlannedWrite } from '../generator.ts';
import { pendingTestFile } from './pending-test.ts';
import { EXIT, info, ok, style, UsageError } from '../output.ts';

const IDENTIFIER = /^[A-Za-z][A-Za-z0-9]*$/;
const UNIT = /^[a-z][a-z0-9-]*$/;
const PREFIX = /^\/[A-Za-z0-9/_:.-]*$/;

function toKebab(value: string): string {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[_\s]+/g, '-')
    .toLowerCase();
}

/** `Users` and `UsersController` both become `UsersController` and `users`. */
function names(input: string): { className: string; stem: string } {
  const base = input.endsWith('Controller') ? input.slice(0, -'Controller'.length) : input;
  if (!IDENTIFIER.test(base)) {
    throw new UsageError(
      `"${input}" is not a valid controller name`,
      'use PascalCase, e.g. Users or UsersController',
    );
  }
  return { className: `${base}Controller`, stem: toKebab(base) };
}

export function controllerTemplate(
  className: string,
  stem: string,
  prefix: string,
  unit: string,
): string {
  return `import { Controller, Get } from '@tsir/router';

/**
 * Generated by \`tsir make:controller\`. Controllers are plain classes: dependencies arrive
 * through the constructor, never from a container lookup.
 */
@Controller('${prefix}', { unit: '${unit}' })
export class ${className} {
  @Get('/', { tags: ['${stem}'], operationId: '${stem}.list' })
  list(): unknown {
    return { data: [] };
  }
}
`;
}

export async function makeControllerCommand(argv: readonly string[]): Promise<number> {
  const args = parseArgs(argv, {
    '--path': {
      type: 'string',
      description: 'route prefix, e.g. /api/users (default /api/<stem>)',
    },
    '--unit': { type: 'string', description: 'deploy unit for its routes (default http)' },
    '--force': { type: 'boolean', description: 'overwrite an existing file' },
    '--dry-run': { type: 'boolean', description: 'print the file that would be written' },
  });
  const input = args.positionals[0];
  if (input === undefined) {
    throw new UsageError('tsir make:controller <Name>', 'e.g. tsir make:controller Users');
  }

  const { className, stem } = names(input);
  const prefix = stringFlag(args, '--path') ?? `/api/${stem}`;
  if (!PREFIX.test(prefix)) {
    throw new UsageError(
      `"${prefix}" is not a valid route prefix`,
      'start it with / , e.g. /api/users',
    );
  }
  const unit = stringFlag(args, '--unit') ?? 'http';
  if (!UNIT.test(unit)) {
    throw new UsageError(
      `"${unit}" is not a valid unit name`,
      'use lowercase letters, digits and -',
    );
  }

  const path = join(process.cwd(), 'src', 'modules', `${stem}.controller.ts`);
  const generated: GeneratedFile[] = [
    { path, contents: controllerTemplate(className, stem, prefix, unit) },
  ];
  // CLI-015: every generated part ships with a test that is red until it is implemented.
  const primary = generated[0];
  if (primary !== undefined) generated.push(pendingTestFile(primary.path, className));
  const dryRun = boolFlag(args, '--dry-run');
  const plan: PlannedWrite[] = await commitWrites(generated, {
    force: boolFlag(args, '--force'),
    dryRun,
  });

  for (const entry of plan) {
    const shown = displayPath(entry.path);
    if (dryRun) info(`  ${style.dim(`would ${entry.action}`)} ${shown}`);
    else ok(`${entry.action === 'overwrite' ? 'overwrote' : 'created'} ${shown}`);
  }
  if (!dryRun) {
    info(
      `  ${style.dim('import it from your app so the route registers:')} ./modules/${stem}.controller.ts`,
    );
  }
  return EXIT.ok;
}
