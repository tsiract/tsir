import { pathToFileURL } from 'node:url';

import { defineCommand, type CommandSpec } from '../define-command.ts';
import { UsageError } from '../output.ts';

/**
 * `ract` (CLI-018, CLI-020): the project's own command runner, the counterpart of `php artisan`.
 *
 * `ract` lives in the project root with no extension, so `bun ract db:seed` works on every OS.
 * It runs the same commands as `tsir`, limited to the names listed in `console.commands` when that
 * key is set. Prettier and eslint cannot parse an extensionless file, so the generated project
 * ignores it by name in its own tooling config.
 */

/** The file `new` and `bootstrap` write. Plain JavaScript: no types, no extension. */
export const RACT_TEMPLATE = `#!/usr/bin/env bun
// Project command runner, generated by tsir. Runs the commands listed in console.commands.
import { runProjectCommand } from '@tsir/console';

process.exitCode = await runProjectCommand(process.argv.slice(2));
`;

/** The mode `ract` must have so it runs as `./ract`. */
export const RACT_MODE = 0o755;

/** Names in `listed` that are not a known command. These fail `tsir doctor` (CLI-020). */
export function unknownConsoleCommands(
  listed: readonly string[],
  known: readonly string[],
): readonly string[] {
  return listed.filter((name) => !known.includes(name));
}

/** The refusal line for a command the project did not list, with the key to edit. */
export function notListedMessage(name: string): { message: string; hint: string } {
  return {
    message: `"${name}" is not listed in console.commands`,
    hint: `add "${name}" to console.commands in tsir.js`,
  };
}

/** True for a value shaped like `defineCommand({...})`: a name, a summary and a run function. */
function isCommandSpec(value: unknown): value is CommandSpec {
  if (typeof value !== 'object' || value === null) return false;
  const candidate = value as Record<string, unknown>;
  return (
    typeof candidate['name'] === 'string' &&
    typeof candidate['summary'] === 'string' &&
    typeof candidate['run'] === 'function'
  );
}

/**
 * The commands an application entry exports as `commands` (CLI-019). Each one is re-validated with
 * `defineCommand`, so an entry that exports a plain object with a bad name fails here, not later.
 */
export function projectCommandsOf(
  entry: Readonly<Record<string, unknown>>,
): readonly CommandSpec[] {
  const exported = entry['commands'];
  if (exported === undefined) return [];
  if (!Array.isArray(exported)) {
    throw new UsageError(
      'the application entry export `commands` must be an array',
      'export `commands = [defineCommand({...})]` from the entry',
    );
  }
  return exported.map((item: unknown, index: number) => {
    if (!isCommandSpec(item)) {
      throw new UsageError(
        `commands[${String(index)}] is not a defineCommand({...})`,
        'each entry in `commands` needs a name, a summary and a run function',
      );
    }
    return defineCommand(item);
  });
}

/** Loads the application entry and returns the project's own commands. */
export async function loadProjectCommands(entryPath: string): Promise<readonly CommandSpec[]> {
  const entry = (await import(pathToFileURL(entryPath).href)) as Readonly<Record<string, unknown>>;
  return projectCommandsOf(entry);
}
