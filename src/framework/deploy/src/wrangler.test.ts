/**
 * `wrangler.*.toml` generation (`DPL-009`, `DPL-010`, `DPL-012`).
 *
 * A generated config is only useful if it is *reviewable*, which means three properties:
 * it is deterministic (a regeneration of an unchanged graph is a no-op), it is least
 * privileged (a unit with no queue binding has no queue section — not an empty one), and it
 * never contains a secret value (only the `wrangler secret put` line that creates it).
 */

import { describe, expect, test } from 'bun:test';
import { TsirError } from '@tsir/core';

import { resolveUnits, type Unit } from './units.ts';
import { wranglerConfigs, wranglerToml, type WranglerOptions } from './wrangler.ts';

const options: WranglerOptions = {
  compatibilityDate: '2026-09-01',
  resources: {
    HYPERDRIVE: { id: 'hd-123' },
    JOBS: { queue: 'acme-jobs' },
    CACHE: { id: 'kv-1' },
    UPLOADS: { bucket: 'acme-uploads' },
    DB: { id: 'db-1', database: 'acme' },
    ROOMS: { className: 'Room' },
  },
  vars: { APP_ENV: 'production' },
};

function unit(partial: Partial<Unit> & Pick<Unit, 'name' | 'kind'>): Unit {
  return {
    modules: [],
    reasons: [],
    triggers: [],
    requires: [],
    bindings: [],
    private: false,
    ...partial,
  };
}

describe('the generated config (DPL-009)', () => {
  test('names the worker, pins the compatibility date, and enables observability', () => {
    const toml = wranglerToml(unit({ name: 'http', kind: 'http' }), 'acme', options);

    expect(toml).toContain('name = "acme-http"');
    expect(toml).toContain('main = "index.js"');
    expect(toml).toContain('compatibility_date = "2026-09-01"');
    expect(toml).toContain('[observability]\nenabled = true');
    expect(toml).toContain('# Generated by `tsir deploy:build` for unit "http" — do not edit.');
  });

  test('a unit with no bindings has no binding sections at all', () => {
    const toml = wranglerToml(unit({ name: 'http', kind: 'http' }), 'acme', options);

    expect(toml).not.toContain('[[hyperdrive]]');
    expect(toml).not.toContain('[[queues.producers]]');
    expect(toml).toContain('[vars]');
  });

  test('bindings are emitted in a stable order, whatever order the unit lists them in', () => {
    const bindings = [
      { kind: 'queue' as const, name: 'JOBS' },
      { kind: 'hyperdrive' as const, name: 'HYPERDRIVE' },
      { kind: 'kv' as const, name: 'CACHE' },
    ];

    const forwards = wranglerToml(unit({ name: 'http', kind: 'http', bindings }), 'acme', options);
    const backwards = wranglerToml(
      unit({ name: 'http', kind: 'http', bindings: [...bindings].reverse() }),
      'acme',
      options,
    );

    expect(forwards).toBe(backwards);
    expect(forwards.indexOf('[[hyperdrive]]')).toBeLessThan(forwards.indexOf('[[kv_namespaces]]'));
    expect(forwards.indexOf('[[kv_namespaces]]')).toBeLessThan(
      forwards.indexOf('[[queues.producers]]'),
    );
  });

  test('every binding kind becomes the section Cloudflare expects', () => {
    const toml = wranglerToml(
      unit({
        name: 'http',
        kind: 'http',
        bindings: [
          { kind: 'hyperdrive', name: 'HYPERDRIVE' },
          { kind: 'd1', name: 'DB' },
          { kind: 'kv', name: 'CACHE' },
          { kind: 'r2', name: 'UPLOADS' },
          { kind: 'queue', name: 'JOBS' },
        ],
      }),
      'acme',
      options,
    );

    expect(toml).toContain('[[hyperdrive]]\nbinding = "HYPERDRIVE"\nid = "hd-123"');
    expect(toml).toContain(
      '[[d1_databases]]\nbinding = "DB"\ndatabase_id = "db-1"\ndatabase_name = "acme"',
    );
    expect(toml).toContain('[[kv_namespaces]]\nbinding = "CACHE"\nid = "kv-1"');
    expect(toml).toContain('[[r2_buckets]]\nbinding = "UPLOADS"\nbucket_name = "acme-uploads"');
    expect(toml).toContain('[[queues.producers]]\nbinding = "JOBS"\nqueue = "acme-jobs"');
  });

  test('a binding with no resource fails with the field to declare', () => {
    const incomplete = unit({
      name: 'http',
      kind: 'http',
      bindings: [{ kind: 'hyperdrive', name: 'HYPERDRIVE' }],
    });

    let thrown: unknown;
    try {
      wranglerToml(incomplete, 'acme', { compatibilityDate: '2026-09-01' });
    } catch (error) {
      thrown = error;
    }

    expect(thrown).toBeInstanceOf(TsirError);
    expect((thrown as TsirError).message).toContain('needs a Hyperdrive id');
    expect((thrown as TsirError).message).toContain('bindings.HYPERDRIVE.id');
  });
});

describe('secrets (DPL-012)', () => {
  test('a secret is a comment, never a value', () => {
    const toml = wranglerToml(
      unit({ name: 'http', kind: 'http', bindings: [{ kind: 'secret', name: 'APP_KEY' }] }),
      'acme',
      options,
    );

    expect(toml).toContain('wrangler secret put APP_KEY');
    // The line is a comment: nothing in the file can be read as the value.
    expect(toml.split('\n').find((line) => line.includes('wrangler secret put'))).toStartWith('#');
    expect(toml).not.toContain('APP_KEY =');
  });

  test('secrets are deduplicated and sorted when a unit declares several', () => {
    const toml = wranglerToml(
      unit({
        name: 'http',
        kind: 'http',
        bindings: [
          { kind: 'secret', name: 'STRIPE_KEY' },
          { kind: 'secret', name: 'APP_KEY' },
          { kind: 'secret', name: 'APP_KEY' },
        ],
      }),
      'acme',
      options,
    );

    const lines = toml.split('\n').filter((line) => line.includes('secret put'));
    expect(lines).toEqual([
      '#   wrangler secret put APP_KEY',
      '#   wrangler secret put STRIPE_KEY',
    ]);
  });

  test('vars are emitted as [vars], sorted', () => {
    const toml = wranglerToml(unit({ name: 'http', kind: 'http' }), 'acme', {
      ...options,
      vars: { ZONE: 'a', APP_ENV: 'production' },
    });

    expect(toml).toContain('[vars]\nAPP_ENV = "production"\nZONE = "a"');
  });
});

describe('durable objects (DPL-010)', () => {
  test('a DO binding emits both the binding and the migration', () => {
    const toml = wranglerToml(
      unit({
        name: 'ws',
        kind: 'ws',
        bindings: [{ kind: 'durable-object', name: 'ROOMS' }],
      }),
      'acme',
      options,
    );

    expect(toml).toContain('[[durable_objects.bindings]]\nname = "ROOMS"\nclass_name = "Room"');
    expect(toml).toContain('[[migrations]]\ntag = "v1"\nnew_sqlite_classes = ["Room"]');
  });

  test('the migration tag is explicit, so adding a class is a reviewed bump', () => {
    const toml = wranglerToml(
      unit({ name: 'ws', kind: 'ws', bindings: [{ kind: 'durable-object', name: 'ROOMS' }] }),
      'acme',
      { ...options, migrationTag: 'v2' },
    );

    expect(toml).toContain('tag = "v2"');
  });

  test('a ws unit with no DO binding gets no migration', () => {
    const toml = wranglerToml(unit({ name: 'ws', kind: 'ws' }), 'acme', options);

    expect(toml).not.toContain('[[migrations]]');
  });
});

describe('the whole graph (DPL-009)', () => {
  test('one config per unit, named after the unit', () => {
    const units = resolveUnits({
      appName: 'acme',
      routes: [{ method: 'GET', path: '/' }],
      connections: [{ name: 'primary', journal: true }],
    });

    const configs = wranglerConfigs(units, 'acme', options);

    expect([...configs.keys()]).toEqual(['wrangler.http.toml', 'wrangler.migrate:primary.toml']);
    expect(configs.get('wrangler.http.toml')).toContain('name = "acme-http"');
  });

  test('the same graph generates the same bytes twice', () => {
    const units = resolveUnits({ appName: 'acme', routes: [{ method: 'GET', path: '/' }] });

    expect(wranglerToml(units[0] as Unit, 'acme', options)).toBe(
      wranglerToml(units[0] as Unit, 'acme', options),
    );
  });
});
