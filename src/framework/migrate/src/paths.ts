/**
 * Where a connection's journal lives (`MIG-015`).
 *
 * Drizzle's `meta/_journal.json` records what was applied to *one* database, so a
 * project with two connections needs two folders. The default connection keeps the
 * conventional path (`migrations/`), and every other connection gets a subfolder
 * named after itself — a rule that is boring on purpose: `migrations/reporting`
 * is guessable, and an existing single-connection project does not move.
 *
 * The alternative — one folder with a `connection` column in the journal — was
 * rejected: the journal is Drizzle's file, generated by `drizzle-kit`, and a
 * hand-maintained column in generated JSON is exactly the kind of drift this
 * package exists to detect.
 */

import { join } from 'node:path';

export interface MigrationPathOptions {
  /** `paths.migrations` from `tsir.js`. Defaults to `migrations`. */
  readonly base?: string;
  /** The registry's default connection — it keeps the unqualified path. */
  readonly defaultConnection?: string;
}

/**
 * The journal folder for `connection`, relative to the project root.
 *
 * A connection named the same as the default always resolves to the base folder,
 * so a project that renames `default` does not silently start reading a new one.
 */
export function migrationFolder(
  root: string,
  connection: string,
  options: MigrationPathOptions = {},
): string {
  const base = options.base ?? 'migrations';
  const isDefault = connection === (options.defaultConnection ?? 'default');
  return isDefault ? join(root, base) : join(root, base, connection);
}

/** True when the folder is the unqualified base — used by CLI output. */
export function isDefaultMigrationFolder(
  connection: string,
  options: MigrationPathOptions = {},
): boolean {
  return connection === (options.defaultConnection ?? 'default');
}
