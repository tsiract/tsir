import type { Container, DiagnosticEvent, Provider, Scope } from '@tsir/container';
import type { LoadedConfig } from '@tsir/config';

import type { RuntimeCapabilities } from './capabilities.ts';
import type { Clock, Random } from './clock.ts';
import type { AppManifest } from './manifest.ts';
import type { ModuleDefinition } from './module.ts';

export type ShutdownReason = 'signal' | 'manual' | 'bootstrap-failed' | 'runtime-error';

/**
 * Application state is a discriminated union so an adapter cannot act on a
 * partially built app: `ready` is the only state that carries registries.
 */
export type AppState<TConfig> =
  | { readonly kind: 'created' }
  | { readonly kind: 'configured'; readonly config: LoadedConfig<TConfig> }
  | { readonly kind: 'composed'; readonly providerCount: number }
  | { readonly kind: 'ready'; readonly readyAt: string }
  | { readonly kind: 'stopping'; readonly reason: ShutdownReason }
  | { readonly kind: 'stopped'; readonly reason: ShutdownReason; readonly durationMs: number }
  | { readonly kind: 'failed'; readonly code: string };

export type AppStage = 'validate' | 'compose' | 'start' | 'ready' | 'stop' | 'dispose';

export type AppDiagnosticEvent =
  | { readonly type: 'stage'; readonly stage: AppStage; readonly durationMs: number }
  | {
      readonly type: 'module';
      readonly module: string;
      readonly hook: 'onStart' | 'onReady' | 'onStop';
      readonly durationMs: number;
    }
  | { readonly type: 'container'; readonly event: DiagnosticEvent };

export interface BootstrapOptions<TConfig> {
  readonly appName: string;
  readonly modules: readonly ModuleDefinition[];
  /** Already-loaded configuration. `loadConfig` produces this. */
  readonly config: LoadedConfig<TConfig>;
  /** Generated by `tsir build`. Required in production, optional in development. */
  readonly manifest?: AppManifest;
  readonly mode?: 'development' | 'production' | 'test';
  /** Test-only substitutions applied before any singleton is constructed. */
  readonly overrides?: readonly Provider<unknown>[];
  readonly clock?: Clock;
  readonly random?: Random;
  readonly signal?: AbortSignal;
  readonly capabilities?: RuntimeCapabilities;
  readonly shutdownTimeoutMs?: number;
  readonly onDiagnostic?: (event: AppDiagnosticEvent) => void;
}

export interface App<TConfig = unknown> {
  readonly appName: string;
  readonly state: AppState<TConfig>;
  readonly config: LoadedConfig<TConfig>;
  readonly manifest: AppManifest | undefined;
  readonly clock: Clock;
  readonly random: Random;
  readonly capabilities: RuntimeCapabilities;
  /**
   * The composition root's container. Boundary code (bootstrap, request
   * scopes, job runners, CLI commands) resolves from it; application classes
   * receive their dependencies through constructors instead.
   */
  readonly container: Container;
  /** Creates a request/job scope. The only sanctioned way to obtain scoped providers. */
  createScope(kind: 'request' | 'job' | 'task', id?: string): Scope;
  /** Idempotent. Repeated calls return the same promise. */
  shutdown(reason: ShutdownReason): Promise<void>;
}
