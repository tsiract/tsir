/**
 * Package scaffolding (FND-020).
 *
 * Every package in this workspace is a manifest plus a barrel plus a test that
 * runs. Creating one by copying a neighbour is how you end up with a package
 * that forgot `sideEffects: false`, or a test file nobody wired into `bun test`.
 * This generates the files and refuses to guess.
 *
 *   bun src/tools/new-package.ts http-client --kind framework
 *   bun src/tools/new-package.ts http-client --dry-run   # print, write nothing
 *
 * The generated package is deliberately *complete but empty*: one exported
 * symbol, one test asserting it. It compiles, it passes `make check`, and the
 * next commit adds the real code. A package that cannot boot is a package that
 * cannot be reviewed.
 */

import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export type PackageKind = 'framework' | 'app';

export interface ScaffoldOptions {
  readonly name: string;
  readonly kind?: PackageKind;
  readonly description?: string;
}

const SLUG = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;

/** Files to create, keyed by path relative to the repository root. */
export function scaffold(options: ScaffoldOptions): Readonly<Record<string, string>> {
  const { name } = options;
  if (!SLUG.test(name)) {
    throw new TypeError(
      `new-package: "${name}" is not a valid package name (lowercase kebab-case, e.g. "http-client")`,
    );
  }

  const kind = options.kind ?? 'framework';
  if (kind !== 'framework' && kind !== 'app') {
    throw new TypeError(`new-package: unknown kind "${String(kind)}" (framework | app)`);
  }

  const description =
    options.description ?? `@tsir/${name} — TODO: one sentence, in the imperative.`;
  const dir = kind === 'framework' ? `src/framework/${name}` : `src/apps/${name}`;
  const ident = name.replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase());
  const constant = ident.charAt(0).toUpperCase() + ident.slice(1);

  const manifest = {
    name: `@tsir/${name}`,
    version: '0.0.0',
    license: 'MIT',
    private: true,
    type: 'module',
    description,
    exports: { '.': { types: './src/index.ts', default: './src/index.ts' } },
    sideEffects: false,
  };

  return {
    [`${dir}/package.json`]: `${JSON.stringify(manifest, null, 2)}\n`,
    [`${dir}/src/index.ts`]:
      `/**\n` +
      ` * ${description}\n` +
      ` *\n` +
      ` * Keep the public surface small: everything exported here is an API promise\n` +
      ` * that \`src/docs/api-surface.json\` records and the release notes must mention.\n` +
      ` */\n\n` +
      `/** Placeholder replaced by the first real feature. */\n` +
      `export const ${ident} = '@tsir/${name}' as const;\n`,
    [`${dir}/src/${name}.test.ts`]:
      `import { describe, expect, test } from 'bun:test';\n\n` +
      `import { ${ident} } from './index.ts';\n\n` +
      `describe('${name}', () => {\n` +
      `  test('the package is wired into the workspace', () => {\n` +
      `    expect(${ident}).toBe('@tsir/${name}');\n` +
      `  });\n` +
      `});\n`,
    [`${dir}/TASKS.md`]:
      `# ${constant} — task list\n\n` +
      `> Generated by \`src/tools/new-package.ts\`. Replace this stub with the real task\n` +
      `> table before the first feature lands.\n\n` +
      `| ID        | Task                   | Status | Depends | Acceptance |\n` +
      `| --------- | ---------------------- | ------ | ------- | ---------- |\n` +
      `| \`PKG-001\` | First real feature | \`[ ]\` | — | Test names the behaviour |\n`,
  };
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  // A flag's value is not a positional: `--kind framework` must not name the package `framework`.
  const valueFlags = new Set(['--kind', '--description']);
  const positional = args.filter(
    (arg, index) => !arg.startsWith('-') && !valueFlags.has(args[index - 1] ?? ''),
  );
  const name = positional[0];
  const dryRun = args.includes('--dry-run');
  const kindIndex = args.indexOf('--kind');
  const kind = kindIndex === -1 ? undefined : (args[kindIndex + 1] as PackageKind | undefined);
  const descriptionIndex = args.indexOf('--description');
  const description = descriptionIndex === -1 ? undefined : args[descriptionIndex + 1];

  if (name === undefined) {
    process.stderr.write(
      'usage: bun src/tools/new-package.ts <name> [--kind framework|app] [--description "..."] [--dry-run]\n',
    );
    process.exit(1);
  }

  let files: Readonly<Record<string, string>>;
  try {
    files = scaffold({
      name,
      ...(kind === undefined ? {} : { kind }),
      ...(description === undefined ? {} : { description }),
    });
  } catch (error: unknown) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  }

  const collisions = Object.keys(files).filter((path) => existsSync(path));
  if (collisions.length > 0) {
    process.stderr.write(`refusing to overwrite:\n${collisions.map((p) => `  ${p}`).join('\n')}\n`);
    process.exit(1);
  }

  for (const [path, content] of Object.entries(files)) {
    if (dryRun) process.stdout.write(`--- ${path}\n${content}`);
    else {
      mkdirSync(join(path, '..'), { recursive: true });
      writeFileSync(path, content);
      process.stdout.write(`  created ${path}\n`);
    }
  }

  if (!dryRun) {
    process.stdout.write(
      `\n  next: add "@tsir/${name}" to src/tools/check-boundaries.ts ALLOWED,\n` +
        '        then `bun install` and `make check`\n',
    );
  }
}
