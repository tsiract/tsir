#!/usr/bin/env bun
/**
 * One reference page per framework package (DOC-010).
 *
 * Writes `src/docs/packages/<name>.md` from the two registries the repository already keeps:
 *
 *   · `src/docs/api-surface.json` — every export of the package, subpaths included
 *   · `src/docs/error-codes.json` — every error code, with the package that owns it
 *
 * Install line, public surface and owned codes are generated, so they cannot drift.
 *
 * The three prose sections — Example, Failure modes, Security notes — are written by hand in
 * `src/docs/packages/prose/<name>.md`. Until a package has that file, each section says
 * `Pending` instead of looking complete. The examples are run by `package-examples.test.ts`,
 * so a broken example fails the suite.
 *
 *   bun src/tools/package-pages.ts           # check (CI)
 *   bun src/tools/package-pages.ts --write   # regenerate
 */

import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const FRAMEWORK = join(ROOT, 'src/framework');
const OUT_DIR = join(ROOT, 'src/docs/packages');
const PROSE_DIR = join(OUT_DIR, 'prose');
const SURFACE = join(ROOT, 'src/docs/api-surface.json');
const CODES = join(ROOT, 'src/docs/error-codes.json');

export const SECTIONS = ['Example', 'Failure modes', 'Security notes'] as const;
export type Section = (typeof SECTIONS)[number];

export interface PackageInfo {
  readonly dir: string;
  readonly name: string;
  /** The manifest's own summary; empty when the package does not declare one. */
  readonly description: string;
}

/** Every framework package: a directory under `src/framework` with its own `package.json`. */
export function listPackages(root: string = FRAMEWORK): PackageInfo[] {
  const out: PackageInfo[] = [];
  for (const dir of readdirSync(root, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    const manifest = join(root, dir.name, 'package.json');
    if (!existsSync(manifest)) continue;
    const parsed = JSON.parse(readFileSync(manifest, 'utf8')) as {
      name?: unknown;
      description?: unknown;
    };
    if (typeof parsed.name !== 'string') continue;
    out.push({
      dir: dir.name,
      name: parsed.name,
      description: typeof parsed.description === 'string' ? parsed.description : '',
    });
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

/** Split a prose file into its three sections. Other headings are ignored. */
export function parseProse(text: string): Partial<Record<Section, string>> {
  const out: Partial<Record<Section, string>> = {};
  for (const part of text.split(/^## /mu).slice(1)) {
    const newline = part.indexOf('\n');
    const title = (newline === -1 ? part : part.slice(0, newline)).trim();
    const body = newline === -1 ? '' : part.slice(newline + 1).trim();
    if ((SECTIONS as readonly string[]).includes(title)) out[title as Section] = body;
  }
  return out;
}

/**
 * Owned codes that the written Failure modes section does not name. A code is named when it
 * appears in backticks there, so a code added to a package cannot ship without an explanation.
 */
export function uncoveredCodes(
  dir: string,
  codes: Readonly<Record<string, string>>,
  prose: string,
): readonly string[] {
  const failures = parseProse(prose)['Failure modes'] ?? '';
  return Object.entries(codes)
    .filter(([, owner]) => owner === dir)
    .map(([code]) => code)
    .filter((code) => !failures.includes(`\`${code}\``))
    .sort();
}

/** The page for one package, as text. Deterministic: the same inputs give the same bytes. */
export function renderPage(
  pkg: PackageInfo,
  surface: Readonly<Record<string, readonly string[]>>,
  codes: Readonly<Record<string, string>>,
  prose?: string,
): string {
  const written = prose === undefined ? {} : parseProse(prose);
  const section = (title: Section, pendingText: string): string =>
    written[title] ?? `_Pending: ${pendingText} for this package is not written yet._`;

  // A surface key is `<dir>` for the barrel and `<dir>:<subpath>` for each subpath entry.
  const entries = Object.keys(surface)
    .filter((key) => key === pkg.dir || key.startsWith(`${pkg.dir}:`))
    .sort((a, b) => (a === pkg.dir ? -1 : b === pkg.dir ? 1 : a.localeCompare(b)));

  const owned = Object.entries(codes)
    .filter(([, owner]) => owner === pkg.dir)
    .map(([code]) => code)
    .sort();

  const lines: string[] = [];
  lines.push(`# \`${pkg.name}\``, '');
  lines.push(
    '<!-- Generated by `bun src/tools/package-pages.ts --write`. Do not edit by hand. -->',
    '',
  );

  lines.push(
    '## Install',
    '',
    'After [installing the distribution](../installation.md), add this package from its workspace in your application:',
    '',
    '```sh',
    `bun add '${pkg.name}@workspace:*'`,
    '```',
    '',
    'The packages are not yet published to npm.',
    '',
  );

  lines.push('## Public surface', '');
  for (const key of entries) {
    const names = surface[key] ?? [];
    const specifier = key === pkg.dir ? pkg.name : `${pkg.name}/${key.slice(pkg.dir.length + 1)}`;
    lines.push(`**\`${specifier}\`**`, '');
    lines.push(
      names.length === 0 ? '_No named exports._' : names.map((n) => `\`${n}\``).join(', '),
    );
    lines.push('');
  }

  lines.push('## Error codes', '');
  if (owned.length === 0) {
    lines.push('This package raises no error codes of its own.', '');
  } else {
    lines.push(
      `Owned by this package (${String(owned.length)}). Each one is described in the [error-code reference](../errors.md).`,
      '',
    );
    for (const code of owned) lines.push(`- \`${code}\``);
    lines.push('');
  }

  lines.push('## Example', '', section('Example', 'a worked example'), '');
  lines.push(
    '## Failure modes',
    '',
    section('Failure modes', 'the conditions behind each code above'),
    '',
  );
  lines.push('## Security notes', '', section('Security notes', 'the security notes'), '');

  return lines.join('\n');
}

/**
 * The package index: every page, grouped by the job it does.
 *
 * The grouping is by role rather than alphabet, because a reader looking for "how do I cache
 * something" does not know the package is called `cache` yet — and the alphabet only answers a
 * question you already know the answer to.
 */
export function renderIndex(packages: readonly PackageInfo[]): string {
  const groups: Record<string, readonly string[]> = {
    Foundations: ['core', 'container', 'config', 'console', 'tui'],
    'HTTP and validation': ['http', 'router', 'validate', 'policy', 'link'],
    Data: ['database', 'migrate', 'seed', 'vault'],
    'Background work': ['queue', 'schedule', 'events', 'pulse', 'telemetry'],
    Services: ['cache', 'storage', 'mail', 'notify', 'scout', 'broadcast', 'media'],
    'Identity and commerce': ['auth', 'socialize', 'cashier', 'pennant'],
    'Deployment and testing': ['deploy', 'testing', 'nightwatch', 'forge'],
  };
  const placed = new Set(Object.values(groups).flat());
  const rest = packages.map((pkg) => pkg.dir).filter((dir) => !placed.has(dir));
  const byDir = new Map(packages.map((pkg) => [pkg.dir, pkg]));
  const list = (dirs: readonly string[]): string[] =>
    dirs.flatMap((dir) => {
      const pkg = byDir.get(dir);
      // A name in a group that no longer exists is dropped, not rendered as a dead link: the
      // groups are hand-maintained and a rename must not silently produce a broken page.
      if (pkg === undefined) return [];
      const summary = pkg.description === '' ? '' : `: ${pkg.description}`;
      return [`- [\`${pkg.name}\`](./${dir}.md)${summary}`];
    });

  const lines = [
    '# Package reference',
    '',
    'Every framework package, one page each: what it supports, what it refuses, and the failure modes',
    'it has. A package page is generated from the package itself — its `package.json`, its exported',
    'surface, and its prose — so it cannot describe a version that no longer exists.',
    '',
    'Looking for which driver a capability uses on your target? That is',
    '[services, drivers, and defaults](../guides/drivers.md).',
    '',
  ];
  for (const [heading, dirs] of Object.entries(groups)) {
    const items = list(dirs);
    if (items.length === 0) continue;
    lines.push(`## ${heading}`, '', ...items, '');
  }
  if (rest.length > 0) lines.push('## Other', '', ...list(rest), '');
  return `${lines.join('\n').trimEnd()}\n`;
}

function main(): number {
  const write = process.argv.includes('--write');
  const packages = listPackages();
  const surface = JSON.parse(readFileSync(SURFACE, 'utf8')) as Record<string, string[]>;
  const codes = (JSON.parse(readFileSync(CODES, 'utf8')) as { codes: Record<string, string> })
    .codes;

  const problems: string[] = [];
  const proseFiles = existsSync(PROSE_DIR)
    ? readdirSync(PROSE_DIR).filter((f) => f.endsWith('.md'))
    : [];
  for (const file of proseFiles) {
    if (!packages.some((pkg) => `${pkg.dir}.md` === file)) {
      problems.push(`prose/${file}: no framework package has this name`);
    }
  }

  const expected = new Map<string, string>();
  for (const pkg of packages) {
    const proseFile = join(PROSE_DIR, `${pkg.dir}.md`);
    const prose = existsSync(proseFile) ? readFileSync(proseFile, 'utf8') : undefined;
    if (prose !== undefined) {
      for (const code of uncoveredCodes(pkg.dir, codes, prose)) {
        problems.push(`${pkg.dir}.md: Failure modes do not name ${code}`);
      }
    }
    expected.set(`${pkg.dir}.md`, renderPage(pkg, surface, codes, prose));
  }

  // An index, because thirty-four pages with no entry point are only reachable from the sidebar.
  expected.set('index.md', renderIndex(packages));

  if (write) {
    mkdirSync(OUT_DIR, { recursive: true });
    for (const [file, text] of expected) writeFileSync(join(OUT_DIR, file), text);
    process.stdout.write(`✓ ${String(expected.size)} package pages written\n`);
    return 0;
  }

  for (const [file, text] of expected) {
    const path = join(OUT_DIR, file);
    if (!existsSync(path)) problems.push(`${file}: missing — run with --write`);
    else if (readFileSync(path, 'utf8') !== text)
      problems.push(`${file}: stale — run with --write`);
  }
  if (existsSync(OUT_DIR)) {
    for (const entry of readdirSync(OUT_DIR, { withFileTypes: true })) {
      if (entry.isFile() && !expected.has(entry.name)) {
        problems.push(`${entry.name}: no package has this name`);
      }
    }
  }

  if (problems.length > 0) {
    process.stderr.write(`package pages are inconsistent (${String(problems.length)}):\n\n`);
    for (const problem of problems) process.stderr.write(`  ✗ ${problem}\n`);
    return 1;
  }
  const withProse = proseFiles.length;
  process.stdout.write(
    `✓ ${String(expected.size)} package pages are current, one per framework package ` +
      `(${String(withProse)} with written prose, ${String(expected.size - withProse)} pending)\n`,
  );
  return 0;
}

if (import.meta.main) process.exit(main());
