                // `AWS/SQS` deleted counter counts. A repeat of a delete that already
                // succeeded deletes nothing, so it counts nothing: the arm below leaves it
                // uncounted.
                queue.count_traffic(sqs::QueueTraffic::MessagesDeleted, 1.0, now);
