            let Some(configuration_set) = store.configuration_sets.get(set_name) else {
                return Err(SendEmailErrorModeled::NotFoundException(NotFoundException {
                    message: Some(crate::state::configuration_set_not_found(set_name)),
                })
                .into());
            };
